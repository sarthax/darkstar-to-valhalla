"""npc_list vs client DAT aligner.
Usage: py -3 tools/dat_align.py host user pw db <out.sql> <pull_dir> [<pull_dir> ...]
Finds npc_list rows whose name differs from the DAT entity at their id, and proposes a move to the slot
(id+offset) where the SAME name sits in the DAT. A move is accepted only if:
  - name match is exact (normalized), or the row is unnamed/placeholder and sits between two rows moving by the same offset
  - the target id is not an occupied npc_list row that is staying put
  - the target id is not a mob_spawn_points row of a different name
Writes UPDATE statements to <out.sql> and prints per-zone stats. Does not touch the DB."""
import sys, re, glob, yaml, collections, mysql.connector as m
h, u, p, d, out = sys.argv[1:6]
N = lambda s: re.sub(r'[^a-z0-9]', '', str(s).lower())
dat = {}
for pd in sys.argv[6:]:
    for f in glob.glob(pd + '/**/entities.yml', recursive=True):
        for e in yaml.safe_load(open(f))['names']: dat[e['id']] = e['name']
Z = lambda i: (i >> 12) & 0xfff
byz = collections.defaultdict(list)
for i, n in dat.items(): byz[Z(i)].append((i, N(n)))
c = m.connect(host=h, user=u, password=p, database=d); q = c.cursor()
q.execute("select npcid,name,polutils_name from npc_list"); rows = q.fetchall()
npc = {r[0]: r for r in rows}
q.execute("select mobid,mobname from mob_spawn_points"); mob = dict(q.fetchall())
PLACE = lambda s: (not N(s)) or re.fullmatch(r'\d+|[0-9a-f]{1,3}', N(s)) is not None or N(s) in ('blank', 'qm1', 'relic', 'npc')
def names(r): return {N(r[1]), N(r[2])} - {''}
bad = {}
for r in rows:
    i = r[0]
    if Z(i) in byz and i in dat and N(dat[i]) and N(dat[i]) not in names(r): bad[i] = r
plan = {}; stats = {}
for z in sorted({Z(i) for i in bad}):
    zb = sorted(i for i in bad if Z(i) == z)
    cand = {}
    for i in zb:
        ns = names(bad[i])
        offs = [j - i for j, dn in byz[z] if dn and dn in ns]
        cand[i] = offs
    cnt = collections.Counter(o for i in zb for o in cand[i])
    assign = {}
    for off, _ in cnt.most_common(12):
        for i in zb:
            if i not in assign and off in cand[i] and not PLACE(bad[i][1]) | (len(cand[i]) > 40):
                assign[i] = off
    # unnamed/placeholder rows: take the offset of neighbours if both sides agree
    allz = sorted(i for i in npc if Z(i) == z)
    for i in zb:
        if i in assign: continue
        k = allz.index(i)
        lo = next((assign.get(allz[j]) for j in range(k - 1, -1, -1) if allz[j] in assign), None)
        hi = next((assign.get(allz[j]) for j in range(k + 1, len(allz)) if allz[j] in assign), None)
        if lo is not None and lo == hi: assign[i] = lo
    moving = set(assign)
    final = {}; skipped = []
    tgt = collections.Counter(i + o for i, o in assign.items())
    for i, o in assign.items():
        t = i + o
        why = None
        if t not in dat: why = 'target has no DAT entity'
        elif tgt[t] > 1: why = 'two rows want the same target'
        elif t in npc and t not in moving: why = 'target occupied by staying npc ' + str(npc[t][1])
        elif t in mob and N(mob[t]) not in names(bad[i]): why = 'target is a different mob ' + mob[t]
        elif not PLACE(bad[i][1]) and N(dat[t]) not in names(bad[i]): why = 'name mismatch'
        if why: skipped.append((i, bad[i][1], why))
        else: final[i] = t
    plan.update(final)
    left = [i for i in zb if i not in final]
    stats[z] = (len(zb), len(final), left, skipped)
tot = 0
for z, (nb, nf, left, sk) in sorted(stats.items(), key=lambda x: -x[1][0]):
    print('zone %d: bad %d, moves %d, leftover %d' % (z, nb, nf, len(left)))
    tot += nf
print('TOTAL moves', tot)
# order so no UPDATE collides with an existing id: topological by dependency (a move whose target is another mover's source goes after it)
order = []; pend = dict(plan)
while pend:
    prog = False
    for i, t in list(pend.items()):
        if t not in pend or t == i:
            order.append((i, t)); del pend[i]; prog = True
    if not prog: raise SystemExit('cycle in moves')
with open(out, 'w') as f:
    f.write('-- generated by tools/dat_align.py: npc_list rows moved onto their client DAT slot (name-verified)\n')
    for i, t in order:
        f.write("UPDATE npc_list SET npcid=%d WHERE npcid=%d;\n" % (t, i))
import pickle
pickle.dump((plan, stats), open(out + '.pkl', 'wb'))
