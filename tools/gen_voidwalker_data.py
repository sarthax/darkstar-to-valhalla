"""Generate scripts/globals/voidwalker_data.lua from the LSB snapshot + textids.csv.

Inputs (read only): LSB zones/*/IDs.lua (VOIDWALKER mob id tables), globals/voidwalkerpos.lua,
docs/slices/voidwalker/textids.csv (client-verified text ids, by TEXT).
Usage: python tools/gen_voidwalker_data.py <lsb_scripts_dir> <textids.csv> <out.lua>
"""
import csv
import glob
import os
import re
import sys


def main(lsb, csv_path, out):
    texts = {r["zone"]: r for r in csv.DictReader(open(csv_path))}
    zones = {}
    for ids in glob.glob(os.path.join(lsb, "zones", "*", "IDs.lua")):
        zone = os.path.basename(os.path.dirname(ids))
        src = open(ids, encoding="utf-8").read()
        m = re.search(r"VOIDWALKER\s*=\s*\n\s*\{(.*?)\n        \}", src, re.S)
        if not m:
            continue
        mobs = {}
        for km in re.finditer(r"\[xi\.keyItem\.(\w+)\]\s*=\s*\{(.*?)\}", m.group(1), re.S):
            rows = re.findall(r"(\d{8})\s*,?\s*(?:--\s*(.*))?", km.group(2))
            mobs[km.group(1)] = [(int(i), (c or "").strip()) for i, c in rows]
        zid = ((next(iter(mobs.values()))[0][0] - 0x1000000) >> 12)
        zones[zone] = (zid, mobs)

    pos_src = open(os.path.join(lsb, "globals", "voidwalkerpos.lua"), encoding="utf-8").read()
    pos = {}
    for zm in re.finditer(r"\[xi\.zone\.(\w+)\]\s*=\s*\n\s*\{(.*?)\n    \},", pos_src, re.S):
        pts = re.findall(r"pos\s*=\s*\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}", zm.group(2))
        pos[zm.group(1)] = [tuple(int(v) for v in p) for p in pts]

    def enum(zone):
        return re.sub(r"_\[S\]$", "_S", zone).upper()

    keys = ["VOIDWALKER_NO_MOB", "VOIDWALKER_MOB_TOO_FAR", "VOIDWALKER_MOB_HINT", "VOIDWALKER_SPAWN_MOB",
            "VOIDWALKER_DESPAWN", "VOIDWALKER_UPGRADE_KI_1", "VOIDWALKER_UPGRADE_KI_2", "VOIDWALKER_BREAK_KI",
            "VOIDWALKER_OBTAIN_KI"]
    L = ["-- GENERATED by tools/gen_voidwalker_data.py - do not hand edit.",
         "-- Text ids: client-verified by TEXT (docs/slices/voidwalker/textids.csv). Mob ids / positions: LSB, positions still need !checknav.",
         "", "VOIDWALKER_DATA = {};", ""]
    for zone in sorted(zones, key=lambda z: zones[z][0]):
        zid, mobs = zones[zone]
        t = texts.get(zone)
        p = pos.get(enum(zone))
        if not t or not p:
            print("SKIP", zone, bool(t), bool(p))
            continue
        L.append(f"VOIDWALKER_DATA[{zid}] = {{ -- {zone}")
        L.append("    text = {")
        for k in keys:
            L.append(f"        {k[len('VOIDWALKER_'):]} = {t[k]},")
        L.append("    },")
        L.append("    mobs = {")
        for ki, rows in mobs.items():
            L.append(f"        [{ki}] = {{")
            for mid, name in rows:
                L.append(f"            {mid}, -- {name}")
            L.append("        },")
        L.append("    },")
        L.append("    pos = {")
        for x, y, z in p:
            L.append(f"        {{ {x}, {y}, {z} }},")
        L.append("    },")
        L.append("};")
        L.append("")
    open(out, "w", newline="\n").write("\n".join(L))
    print("zones written:", sum(1 for z in zones if z in texts and enum(z) in pos))


if __name__ == "__main__":
    main(*sys.argv[1:4])
